/**
 * Media providers supported by FrameHost.
 */
export type MediaProvider = "YOUTUBE" | "LOCAL";

/**
 * Common playback status.
 */
export type MediaPlaybackStatus =
  | "IDLE"
  | "PLAYING"
  | "PAUSED"
  | "BUFFERING"
  | "ENDED";

/**
 * Media source information.
 *
 * A local File is available only on the device
 * that selected it. Never send the File object
 * or its object URL through WebSocket.
 */
export type MediaSource =
  | {
      provider: "YOUTUBE";
      videoId: string;
      title?: string;
    }
  | {
      provider: "LOCAL";
      file: File;
      sessionId?: string;
    };

/**
 * Provider-neutral playback snapshot.
 */
export interface MediaPlaybackSnapshot {
  provider: MediaProvider;
  status: MediaPlaybackStatus;
  currentTime: number;
  duration: number;
  playbackRate: number;
}

/**
 * Standard playback commands.
 */
export type MediaCommandType =
  | "LOAD"
  | "PLAY"
  | "PAUSE"
  | "SEEK"
  | "SET_PLAYBACK_RATE";

/**
 * Playback event generated by a media provider.
 */
export interface MediaPlaybackEvent {
  provider: MediaProvider;
  command: MediaCommandType;
  currentTime?: number;
  playbackRate?: number;
  mediaId?: string;
}

/**
 * Capabilities supported by each provider.
 */
export interface MediaPlayerCapabilities {
  canPlay: boolean;
  canPause: boolean;
  canSeek: boolean;
  canChangePlaybackRate: boolean;
  canShareRemotely: boolean;
}
